const TRANSPORT_CODES = new Set(['connection_closed', 'write_failed', 'request_timeout', 'local_transport_error', 'authentication_failed'])
export function recordShutdownFailure(capture, stage, error, at) {
  capture.failures ??= []
  capture.failures.push({ stage, at, invariant: INVARIANTS.has(error?.message) ? error.message : 'unclassified_failure',
    type: error?.name === 'LocalIpcError' ? 'LocalIpcError' : 'Error',
    code: TRANSPORT_CODES.has(error?.code) ? error.code : null })
}
