import { isVerifiedHostAncestor } from "./protected-namespace-entry.mjs"
import { lstatSync, mkdirSync, realpathSync, writeFileSync, readFileSync, constants, openSync, closeSync, fsyncSync, chownSync } from "node:fs"
import { join, resolve, parse } from "node:path"

function refuse() { throw new Error("Protected slice identity storage is unavailable; existing identity must be restored before this slice can start") }

export function verifyPrivateHostDirectory(path, owner, traversalOnly = false) {
  const absolute = resolve(path)
  if (absolute !== path || realpathSync(path) !== path) refuse()
  let current = parse(path).root
  for (const component of path.slice(current.length).split("/").filter(Boolean)) {
    current = join(current, component)
    const metadata = lstatSync(current)
    if (!metadata.isDirectory() || metadata.isSymbolicLink() || (metadata.mode & 0o022) !== 0) refuse()
    if (metadata.uid !== 0 && metadata.uid !== owner && !isVerifiedHostAncestor(current, metadata)) refuse()
  }
  const leaf = lstatSync(path)
  if (leaf.uid !== owner || (traversalOnly ? (leaf.mode & 0o777) !== 0o711 : (leaf.mode & 0o077) !== 0)) refuse()
  return path
}

// Called only for proven fresh provisioning; never as a recovery fallback.
// No private file is read, copied, deleted or generated by this helper.
export function preparePrivateHostRoot(root, sliceId, owner, fresh, dataOwner = owner) {
  verifyPrivateHostDirectory(root, owner, (lstatSync(root).mode & 0o777) === 0o711)
  if (!/^[A-Za-z0-9][A-Za-z0-9_.:-]{0,179}$/.test(sliceId)) refuse()
  const directory = join(root, sliceId)
  const layouts = join(root, ".layouts")
  try { mkdirSync(layouts, {mode: 0o700}) } catch (error) { if (error.code !== "EEXIST") throw error }
  verifyPrivateHostDirectory(layouts, owner)
  const marker = join(layouts, `${sliceId}.json`)
  if (!fresh) {
    verifyPrivateHostDirectory(directory, dataOwner)
    const metadata = lstatSync(marker)
    if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.nlink !== 1 || metadata.uid !== owner || (metadata.mode & 0o077) !== 0) refuse()
    const receipt = JSON.parse(readFileSync(marker, "utf8"))
    if (receipt.version !== 1 || receipt.sliceId !== sliceId || receipt.owner !== owner || receipt.dataOwner !== dataOwner) refuse()
    // Runtime identity existence is checked against its recorded public paths by
    // the provisioner before restart; missing state is never initialized here.
    return directory
  }
  // Non-recursive mkdir is intentional: an existing root is not fresh.
  mkdirSync(directory, { mode: 0o700 })
  if (dataOwner !== owner) chownSync(directory, dataOwner, dataOwner)
  for (const child of ["kernel", "kernel/state", "kernel/state/daemon", "kernel/kernels", "kernel/machine", "provider-home", "provider-accounts", "nssdb", "runtime"]) {
    const path = join(directory, child)
    mkdirSync(path, { mode: 0o700 })
    if (dataOwner !== owner) chownSync(path, dataOwner, dataOwner)
  }
  const fd = openSync(marker, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600)
  try { writeFileSync(fd, JSON.stringify({ version: 1, sliceId, owner, dataOwner })); fsyncSync(fd) } finally { closeSync(fd) }
  return directory
}
