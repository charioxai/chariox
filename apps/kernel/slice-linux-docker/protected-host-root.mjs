import { lstatSync, mkdirSync, realpathSync, writeFileSync, readFileSync, constants, openSync, closeSync, fsyncSync } from "node:fs"
import { join, resolve, parse } from "node:path"

function refuse() { throw new Error("Protected slice identity storage is unavailable; existing identity must be restored before this slice can start") }

export function verifyPrivateHostDirectory(path, owner) {
  const absolute = resolve(path)
  if (absolute !== path || realpathSync(path) !== path) refuse()
  let current = parse(path).root
  for (const component of path.slice(current.length).split("/").filter(Boolean)) {
    current = join(current, component)
    const metadata = lstatSync(current)
    if (!metadata.isDirectory() || metadata.isSymbolicLink() || (metadata.mode & 0o022) !== 0) refuse()
    if (metadata.uid !== 0 && metadata.uid !== owner) refuse()
  }
  const leaf = lstatSync(path)
  if (leaf.uid !== owner || (leaf.mode & 0o077) !== 0) refuse()
  return path
}

// Called only for proven fresh provisioning; never as a recovery fallback.
// No private file is read, copied, deleted or generated by this helper.
export function preparePrivateHostRoot(root, sliceId, owner, fresh) {
  verifyPrivateHostDirectory(root, owner)
  if (!/^[A-Za-z0-9_.:-]{1,180}$/.test(sliceId)) refuse()
  const directory = join(root, sliceId)
  const marker = join(directory, "layout.json")
  if (!fresh) {
    verifyPrivateHostDirectory(directory, owner)
    const metadata = lstatSync(marker)
    if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.nlink !== 1 || metadata.uid !== owner || (metadata.mode & 0o077) !== 0) refuse()
    const receipt = JSON.parse(readFileSync(marker, "utf8"))
    if (receipt.version !== 1 || receipt.sliceId !== sliceId || receipt.owner !== owner) refuse()
    // Runtime identity existence is checked against its recorded public paths by
    // the provisioner before restart; missing state is never initialized here.
    return directory
  }
  // Non-recursive mkdir is intentional: an existing root is not fresh.
  mkdirSync(directory, { mode: 0o700 })
  for (const child of ["kernel", "provider-home", "provider-accounts", "nssdb", "runtime"]) mkdirSync(join(directory, child), { mode: 0o700 })
  const fd = openSync(marker, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600)
  try { writeFileSync(fd, JSON.stringify({ version: 1, sliceId, owner })); fsyncSync(fd) } finally { closeSync(fd) }
  return directory
}
