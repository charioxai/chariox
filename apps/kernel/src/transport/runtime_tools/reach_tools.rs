//! The `chariox-reach` MCP server: how a kernel owner's Room agent reaches other
//! rooms and kernels. The specs and arguments only; the kernel authorizes each call
//! against the agent's own live run.

use serde::Deserialize;

use super::*;

pub const REACH_KERNELS_TOOL: &str = "kernels";
pub const REACH_SESSIONS_TOOL: &str = "sessions";
pub const REACH_REQUEST_TOOL: &str = "request";
pub const REACH_EVENTS_SUBSCRIBE_TOOL: &str = "events_subscribe";
pub const REACH_EVENTS_WAIT_TOOL: &str = "events_wait";
pub const REACH_EVENTS_ACK_TOOL: &str = "events_ack";
pub const REACH_GUIDE_TOOL: &str = "guide";

/// The longest an `events_wait` lasts: a provider ends a tool call that lasts longer.
const REACH_EVENTS_WAIT_MAX_SECONDS: u64 = 280;
const REACH_EVENTS_WAIT_DEFAULT_SECONDS: u64 = 60;

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReachRequestArgs {
    /// The kernel to ask, as `kernels` names it; absent means this kernel.
    #[serde(default)]
    pub kernel: Option<String>,
    /// One externally tagged kernel request, for example `{"ListSessions":null}`.
    pub request: Value,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReachSessionsArgs {
    #[serde(default)]
    pub kernel: Option<String>,
    /// One room: list its agents instead of the rooms.
    #[serde(default)]
    pub session_id: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReachEventsSubscribeArgs {
    pub kernel: String,
    pub session_id: String,
    #[serde(default)]
    pub agent_id: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReachEventsWaitArgs {
    #[serde(default)]
    pub since: Option<u64>,
    #[serde(default)]
    pub limit: Option<usize>,
    #[serde(default)]
    pub timeout_seconds: Option<u64>,
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ReachEventsAckArgs {
    pub cursor: u64,
}

/// The tools of `chariox-reach` as the CLI command table generates them
/// (`scripts/generate-reach-tools.mjs`), with the guide and the example requests.
#[derive(Debug, Deserialize)]
struct ReachToolsDocument {
    tools: Vec<ReachToolEntry>,
    examples: Vec<ReachExample>,
    guide: String,
}

#[derive(Debug, Deserialize)]
struct ReachToolEntry {
    name: String,
    description: String,
    input_schema: Value,
}

#[derive(Debug, Deserialize)]
struct ReachExample {
    pub request: Value,
}

fn document() -> &'static ReachToolsDocument {
    static DOCUMENT: std::sync::OnceLock<ReachToolsDocument> = std::sync::OnceLock::new();
    DOCUMENT.get_or_init(|| {
        serde_json::from_str(include_str!("reach_tools.json"))
            .expect("reach_tools.json is generated by scripts/generate-reach-tools.mjs")
    })
}

pub fn reach_tool_specs() -> Vec<RuntimeToolSpec> {
    document()
        .tools
        .iter()
        .map(|tool| RuntimeToolSpec {
            name: tool.name.clone(),
            description: tool.description.clone(),
            input_schema: tool.input_schema.clone(),
        })
        .collect()
}

pub fn reach_guide() -> &'static str {
    &document().guide
}

pub fn reach_examples() -> impl Iterator<Item = &'static Value> {
    document().examples.iter().map(|example| &example.request)
}

/// `events_wait` as the request the home kernel's inbox answers.
pub fn reach_events_wait_request(args: ReachEventsWaitArgs) -> Value {
    let seconds = args
        .timeout_seconds
        .unwrap_or(REACH_EVENTS_WAIT_DEFAULT_SECONDS)
        .min(REACH_EVENTS_WAIT_MAX_SECONDS);
    let mut wait = serde_json::json!({
        "timeout_ms": seconds * 1000,
        "limit": args.limit.unwrap_or(1000).clamp(1, 1000),
    });
    if let Some(since) = args.since {
        wait["since"] = since.into();
    }
    serde_json::json!({"WaitEvents": wait})
}

/// `events_subscribe` as the request the home kernel's inbox answers.
pub fn reach_events_subscribe_request(args: ReachEventsSubscribeArgs) -> Value {
    let mut target = serde_json::json!({"kernel": args.kernel, "session_id": args.session_id});
    if let Some(agent_id) = args.agent_id {
        target["agent_id"] = agent_id.into();
    }
    serde_json::json!({"SubscribeEvents": {"targets": [target]}})
}

pub fn reach_events_ack_request(args: ReachEventsAckArgs) -> Value {
    serde_json::json!({"AckEvents": {"cursor": args.cursor}})
}

/// `sessions` as the request that lists the rooms, or one room's agents.
pub fn reach_sessions_request(args: &ReachSessionsArgs) -> Value {
    match &args.session_id {
        Some(session_id) => serde_json::json!({"ListAgents": {"session_id": session_id}}),
        None => serde_json::json!({"ListSessions": null}),
    }
}
