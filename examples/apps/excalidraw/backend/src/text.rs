//! Text metrics and wrapping for bound labels, the part of Excalidraw's layout that the backend
//! repeats without a canvas: the width of a line is the sum of the advances of the Virgil face
//! (`virgil.json`, measured with `scripts/golden.mjs`), the height is lines times the line height,
//! and wrapping follows `wrapText` of Excalidraw 0.18.1 for the break opportunities of Latin text
//! (before and after white space, after a hyphen) and of CJK characters.

use serde_json::Value;
use std::sync::OnceLock;

pub const LINE_HEIGHT: f64 = 1.25;

struct Advances {
    /// Advance of a character at a font size of 1.
    by_char: std::collections::HashMap<char, f64>,
    /// What a character without a measured advance counts as.
    fallback: f64,
}

fn advances() -> &'static Advances {
    static TABLE: OnceLock<Advances> = OnceLock::new();
    TABLE.get_or_init(|| {
        let table: Value = serde_json::from_str(include_str!("virgil.json"))
            .expect("virgil.json is generated by scripts/golden.mjs");
        let per_size = table["measuredAt"]
            .as_f64()
            .expect("virgil.json names the font size it was measured at");
        let by_char = table["advances"]
            .as_object()
            .expect("virgil.json lists advances")
            .iter()
            .map(|(key, width)| {
                (
                    key.chars().next().expect("a character"),
                    width.as_f64().expect("a width") / per_size,
                )
            })
            .collect();
        Advances {
            by_char,
            fallback: table["fallback"].as_f64().expect("a fallback advance") / per_size,
        }
    })
}

fn char_width(c: char, size: f64) -> f64 {
    let table = advances();
    table.by_char.get(&c).copied().unwrap_or(table.fallback) * size
}

pub fn line_width(line: &str, size: f64) -> f64 {
    line.chars().map(|c| char_width(c, size)).sum()
}

/// Excalidraw's `normalizeText`: tabs become eight spaces and line ends become `\n`.
pub fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
        .replace('\r', "\n")
        .replace('\t', "        ")
}

/// Width and height of `text`: an empty line counts as one space.
pub fn measure(text: &str, size: f64, line_height: f64) -> (f64, f64) {
    let lines: Vec<&str> = text.split('\n').collect();
    let width = lines
        .iter()
        .map(|line| line_width(if line.is_empty() { " " } else { line }, size))
        .fold(0.0, f64::max);
    (width, size * line_height * lines.len() as f64)
}

fn is_cjk(c: char) -> bool {
    matches!(c as u32,
        0x2E80..=0x2FDF | 0x3040..=0x30FF | 0x3100..=0x312F | 0x3130..=0x318F | 0x31F0..=0x31FF
        | 0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0xAC00..=0xD7AF | 0xF900..=0xFAFF
        | 0xFF66..=0xFF9F | 0x20000..=0x2FA1F)
}

/// Pieces a line may be broken between: white space is a piece of its own, a hyphen ends its piece
/// and every CJK character is one.
fn tokens(line: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let mut current = String::new();
    let flush = |current: &mut String, tokens: &mut Vec<String>| {
        if !current.is_empty() {
            tokens.push(std::mem::take(current));
        }
    };
    for c in line.chars() {
        if c.is_whitespace() || is_cjk(c) {
            flush(&mut current, &mut tokens);
            tokens.push(c.to_string());
        } else {
            current.push(c);
            if c == '-' {
                flush(&mut current, &mut tokens);
            }
        }
    }
    flush(&mut current, &mut tokens);
    tokens
}

fn wrap_word(word: &str, size: f64, max_width: f64) -> Vec<String> {
    let mut lines = Vec::new();
    let (mut line, mut width) = (String::new(), 0.0);
    for c in word.chars() {
        let advance = char_width(c, size);
        if width + advance <= max_width {
            line.push(c);
            width += advance;
            continue;
        }
        if !line.is_empty() {
            lines.push(std::mem::take(&mut line));
        }
        line.push(c);
        width = advance;
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}

/// Whitespace past the width is dropped, like a browser does, but the room left is still used.
fn trim_line(line: &str, size: f64, max_width: f64) -> String {
    if line_width(line, size) <= max_width {
        return line.to_owned();
    }
    let trimmed = line.trim_end();
    let mut kept = trimmed.to_owned();
    let mut width = line_width(trimmed, size);
    for space in line[trimmed.len()..].chars() {
        let next = width + char_width(space, size);
        if next > max_width {
            break;
        }
        kept.push(space);
        width = next;
    }
    kept
}

fn wrap_line(line: &str, size: f64, max_width: f64) -> Vec<String> {
    let mut lines = Vec::new();
    let (mut current, mut current_width) = (String::new(), 0.0);
    let mut pending = tokens(line).into_iter().peekable();
    while let Some(token) = pending.peek().cloned() {
        let test_width = current_width + line_width(&token, size);
        if token.chars().all(char::is_whitespace) || test_width <= max_width {
            current.push_str(&token);
            current_width = test_width;
            pending.next();
            continue;
        }
        if current.is_empty() {
            let mut word = wrap_word(&token, size, max_width);
            current = word.pop().unwrap_or_default();
            lines.append(&mut word);
            current_width = line_width(&current, size);
            pending.next();
        } else {
            lines.push(current.trim_end().to_owned());
            current.clear();
            current_width = 0.0;
        }
    }
    if !current.is_empty() {
        lines.push(trim_line(&current, size, max_width));
    }
    lines
}

/// `text` broken into lines no wider than `max_width`, at the break opportunities of its words.
pub fn wrap(text: &str, size: f64, max_width: f64) -> String {
    if !max_width.is_finite() || max_width < 0.0 {
        return text.to_owned();
    }
    text.split('\n')
        .flat_map(|line| {
            if line_width(line, size) <= max_width {
                vec![line.to_owned()]
            } else {
                wrap_line(line, size, max_width)
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_line_is_as_wide_as_its_advances_and_text_as_high_as_its_lines() {
        let (width, height) = measure("ab\nabcd", 20.0, LINE_HEIGHT);
        assert_eq!(height, 50.0);
        assert!((width - line_width("abcd", 20.0)).abs() < 1e-9);
        assert_eq!(measure("", 20.0, LINE_HEIGHT).0, line_width(" ", 20.0));
        assert_eq!(normalize("a\tb\r\nc"), "a        b\nc");
    }

    #[test]
    fn wrapping_breaks_between_words_and_after_hyphens_and_never_inside_a_fitting_word() {
        let room = line_width("world-", 20.0) + 0.5;
        let wrapped = wrap("hello world-wide web", 20.0, room);
        assert!(wrapped.lines().any(|line| line == "world-"), "{wrapped:?}");
        assert!(
            wrapped.lines().all(|line| line_width(line, 20.0) <= room),
            "{wrapped:?}"
        );
        assert_eq!(
            wrapped.replace('\n', " ").replace("  ", " "),
            "hello world- wide web"
        );
        assert_eq!(wrap("short", 20.0, 1000.0), "short");
        assert_eq!(wrap("a b", 20.0, f64::NAN), "a b");
    }

    #[test]
    fn a_word_wider_than_the_line_is_cut_by_characters() {
        let one = line_width("m", 20.0);
        let wrapped = wrap("mmmmmm", 20.0, one * 2.5);
        assert_eq!(wrapped, "mm\nmm\nmm");
    }
}
